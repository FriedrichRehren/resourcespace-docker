<?php

/**
 * Writes ResourceSpace's include/config.php from environment variables.
 *
 * Called by rs-entrypoint at every container start, so the file always
 * reflects the current environment. Custom settings that should survive go
 * into /data/config/config.local.php, which is included at the end.
 *
 * Usage: php write-config.php /var/www/html/include/config.php
 */

if (PHP_SAPI !== 'cli') {
    exit(1);
}

$target = $argv[1] ?? '';
if ($target === '') {
    fwrite(STDERR, "Usage: php write-config.php <target>\n");
    exit(1);
}

function env_value(string $name, ?string $default = null): ?string
{
    $value = getenv($name);
    return ($value === false || $value === '') ? $default : $value;
}

function required(string $name): string
{
    $value = env_value($name);
    if ($value === null) {
        fwrite(STDERR, "FEHLER: Umgebungsvariable {$name} ist nicht gesetzt.\n");
        exit(1);
    }
    return $value;
}

function php_value($value): string
{
    return var_export($value, true);
}

$baseurl = rtrim(required('RS_BASEURL'), '/');
if (!preg_match('#^https?://[^/]+#', $baseurl)) {
    fwrite(STDERR, "FEHLER: RS_BASEURL muss mit http:// oder https:// beginnen.\n");
    exit(1);
}

$scramble_key     = required('RS_SCRAMBLE_KEY');
$api_scramble_key = required('RS_API_SCRAMBLE_KEY');

$settings = [
    // Database
    'mysql_server'     => env_value('RS_DB_HOST', 'mariadb'),
    'mysql_username'   => env_value('RS_DB_USER', 'resourcespace'),
    'mysql_password'   => required('RS_DB_PASSWORD'),
    'mysql_db'         => env_value('RS_DB_NAME', 'resourcespace'),

    // URLs and storage (data volume, outside the web root)
    'baseurl'          => $baseurl,
    'storagedir'       => '/data/filestore',
    'storageurl'       => $baseurl . '/filestore',
    'tempdir'          => '/data/tmp',

    // Secrets – must never change after the first start (password hashes depend on them)
    'scramble_key'     => $scramble_key,
    'api_scramble_key' => $api_scramble_key,

    // General
    'applicationname'  => env_value('RS_APPLICATION_NAME', 'ResourceSpace'),
    'defaultlanguage'  => env_value('RS_DEFAULT_LANGUAGE', 'de'),
    'email_from'       => env_value('RS_EMAIL_FROM', 'noreply@' . (parse_url($baseurl, PHP_URL_HOST) ?: 'localhost')),
    'email_notify'     => env_value('RS_ADMIN_EMAIL', ''),

    // Tools inside the image
    'imagemagick_path' => '/usr/bin',
    'ghostscript_path' => '/usr/bin',
    'ffmpeg_path'      => '/usr/bin',
    'exiftool_path'    => '/usr/bin',
    'pdftotext_path'   => '/usr/bin',

    // Slideshow images live in the filestore; folder name derived from the scramble key
    'homeanim_folder'  => 'filestore/system/slideshow_' . substr(md5('slideshow_' . $scramble_key), 0, 15),
];

$port = env_value('RS_DB_PORT');
if ($port !== null) {
    $settings['mysql_server_port'] = (int) $port;
}

$smtp_host = env_value('RS_SMTP_HOST');
if ($smtp_host !== null) {
    $settings['use_smtp']      = true;
    $settings['use_phpmailer'] = true;
    $settings['smtp_host']     = $smtp_host;
    $settings['smtp_port']     = (int) env_value('RS_SMTP_PORT', '587');
    $settings['smtp_secure']   = env_value('RS_SMTP_SECURE', 'tls');
    $smtp_user = env_value('RS_SMTP_USER');
    if ($smtp_user !== null) {
        $settings['smtp_auth']     = true;
        $settings['smtp_username'] = $smtp_user;
        $settings['smtp_password'] = env_value('RS_SMTP_PASSWORD', '');
    }
}

$out  = "<?php\n";
$out .= "###############################################################################\n";
$out .= "# Generated by rs-entrypoint – DO NOT EDIT, overwritten at every container start.\n";
$out .= "# Change settings via environment variables or /data/config/config.local.php.\n";
$out .= "###############################################################################\n\n";

foreach ($settings as $name => $value) {
    $out .= '$' . $name . ' = ' . php_value($value) . ";\n";
}

// Defaults the official setup writes for new installations (version-specific)
$new_installs = (getenv('RS_WEBROOT') ?: '/var/www/html') . '/include/config.new_installs.php';
if (is_file($new_installs)) {
    $defaults = file_get_contents($new_installs);
    $defaults = preg_replace('/^\s*<\?php/', '', $defaults);
    $out .= "\n# ---- Defaults for new installations (include/config.new_installs.php) ----\n";
    $out .= $defaults . "\n";
}

$out .= "\n# ---- Local overrides (persistent, in the data volume) ----\n";
$out .= "if (is_file('/data/config/config.local.php')) {\n";
$out .= "    include '/data/config/config.local.php';\n";
$out .= "}\n";

$tmp = $target . '.tmp';
if (file_put_contents($tmp, $out) === false || !rename($tmp, $target)) {
    fwrite(STDERR, "FEHLER: {$target} konnte nicht geschrieben werden.\n");
    exit(1);
}

exit(0);
